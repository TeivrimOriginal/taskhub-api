"""Operational CLI: `python -m app.cli <command>`.

Commands are plain functions so they can be unit-tested and reused from the Docker
entrypoint (`entrypoint.sh` calls `create-admin` on first boot).
"""

from __future__ import annotations

import argparse
import asyncio
import sys
import uuid
from collections.abc import Sequence

from app.core.config import get_settings
from app.core.constants import ActivityAction, Role, TaskPriority, TaskStatus
from app.core.logging import configure_logging, get_logger
from app.core.security import hash_password
from app.db.session import dispose_engine, session_scope
from app.models.activity_log import ActivityLog
from app.models.project import Project
from app.models.tag import Tag
from app.models.task import Task
from app.models.user import User
from app.repositories.user import UserRepository

logger = get_logger(__name__)


async def create_admin(
    *,
    email: str | None = None,
    password: str | None = None,
    full_name: str | None = None,
) -> User:
    """Create the bootstrap administrator from the environment settings.

    Idempotent: if an account with that e-mail already exists it is promoted to admin
    instead of failing, so re-running the entrypoint on every boot is safe.
    """
    settings = get_settings()
    admin_email = (email or settings.first_superuser_email).strip().lower()
    admin_password = password or settings.first_superuser_password.get_secret_value()

    async with session_scope() as session:
        users = UserRepository(session)
        existing = await users.get_by_email_or_username(admin_email)
        if existing is not None:
            if existing.role is not Role.ADMIN or not existing.is_superuser:
                existing.role = Role.ADMIN
                existing.is_superuser = True
                existing.is_active = True
                existing.deleted_at = None
                await session.flush()
                logger.info("admin_promoted", email=admin_email)
                return existing
            logger.info("admin_already_present", email=admin_email)
            return existing

        admin = User(
            email=admin_email,
            username=admin_email.split("@")[0],
            full_name=full_name or settings.first_superuser_name,
            hashed_password=hash_password(admin_password, rounds=settings.bcrypt_rounds),
            role=Role.ADMIN,
            is_superuser=True,
            is_active=True,
        )
        await users.insert(admin)
        logger.info("admin_created", email=admin_email)
        return admin


async def seed_demo(
    *,
    email: str = "demo@taskhub.dev",
    password: str = "Demo12345!",  # noqa: S107 - a local fixture, documented in the README
    tasks: int = 12,
) -> User:
    """Fill the database with one demo user, projects, tasks, tags and comments.

    Deterministic on purpose (fixed UUID seeds): running it twice does not double the
    data, which keeps a fresh checkout reproducible.
    """
    async with session_scope() as session:
        users = UserRepository(session)
        user = await users.get_by_email_or_username(email)
        if user is None:
            user = User(
                email=email,
                username="demo",
                full_name="Demo User",
                hashed_password=hash_password(password, rounds=get_settings().bcrypt_rounds),
            )
            await users.insert(user)
            logger.info("demo_user_created", email=email)
        else:
            logger.info("demo_user_exists", email=email)

        if await session.get(Project, uuid.UUID(int=0xD3A0)) is not None:
            logger.info("demo_data_already_present")
            return user

        project = Project(
            id=uuid.UUID(int=0xD3A0),
            owner_id=user.id,
            name="Demo project",
            description="Seeded by `python -m app.cli seed-demo`",
            color="#4F46E5",
            last_activity_at=None,
        )
        session.add(project)

        tag_names = ("backend", "urgent", "documentation")
        tags = [Tag(name=name, created_by=user.id) for name in tag_names]
        session.add_all(tags)
        await session.flush()

        statuses = list(TaskStatus)
        priorities = list(TaskPriority)
        for index in range(tasks):
            session.add(
                Task(
                    project_id=project.id,
                    title=f"Demo task #{index + 1}",
                    description="Generated by the seed command",
                    status=statuses[index % len(statuses)],
                    priority=priorities[index % len(priorities)],
                    position=index,
                    tags=[tags[index % len(tags)]],
                )
            )
        await session.flush()

        session.add(
            ActivityLog(
                user_id=user.id,
                task_id=None,
                action=ActivityAction.PROJECT_CREATED.value,
                entity_type="project",
                entity_id=project.id,
                payload={"seeded": True, "tasks": tasks},
            )
        )
        await session.commit()
        logger.info("demo_seeded", tasks=tasks, tags=len(tags), email=email)
        return user


async def show_settings() -> dict[str, str]:
    """Print the effective configuration with every secret masked."""
    settings = get_settings()
    return {
        "app_name": settings.app_name,
        "environment": settings.environment.value,
        "debug": str(settings.debug),
        "api_v1_prefix": settings.api_v1_prefix,
        "log_level": settings.log_level,
        "database": settings.masked_async_dsn(),
        "redis": settings.dsn_for(settings.redis_url),
        "celery_broker": settings.dsn_for(settings.celery_broker_url),
        "rate_limit": (
            f"{settings.rate_limit_requests}/{settings.rate_limit_window_seconds}s"
            f" (enabled={settings.rate_limit_enabled})"
        ),
        "cache": f"enabled={settings.cache_enabled}, ttl={settings.cache_ttl_seconds}s",
        "bcrypt_rounds": str(settings.bcrypt_rounds),
    }


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="taskhub",
        description="TaskHub operational commands",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    admin = sub.add_parser("create-admin", help="Create or promote the bootstrap admin")
    admin.add_argument("--email")
    admin.add_argument("--password")
    admin.add_argument("--full-name")

    demo = sub.add_parser("seed-demo", help="Insert a deterministic demo data set")
    demo.add_argument("--email", default="demo@taskhub.dev")
    demo.add_argument("--password", default="Demo12345!")
    demo.add_argument("--tasks", type=int, default=12)

    sub.add_parser("show-settings", help="Print the effective configuration (masked)")

    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point for `python -m app.cli` and the `taskhub` console script."""
    args = _parse_args(argv)
    configure_logging(level=get_settings().log_level, json_logs=False)

    async def _run() -> int:
        try:
            if args.command == "create-admin":
                admin = await create_admin(
                    email=args.email,
                    password=args.password,
                    full_name=args.full_name,
                )
                print(f"admin ready: {admin.email}")
            elif args.command == "seed-demo":
                user = await seed_demo(
                    email=args.email,
                    password=args.password,
                    tasks=args.tasks,
                )
                print(f"demo data ready for {user.email}")
            elif args.command == "show-settings":
                for key, value in (await show_settings()).items():
                    print(f"{key:>14}: {value}")
            return 0
        finally:
            await dispose_engine()

    return asyncio.run(_run())


if __name__ == "__main__":
    sys.exit(main())
